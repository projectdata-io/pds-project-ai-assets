import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const rootPath = fileURLToPath(new URL("../", import.meta.url));
const catalog = JSON.parse(readFileSync(join(rootPath, "catalog.json"), "utf8"));
const outputPath = join(rootPath, "site", "static", "m365");
const artifactPath = join(rootPath, "dist", "m365-agent-packages");

mkdirSync(outputPath, { recursive: true });

for (const agent of catalog.agents) {
  const packageSlug = `teams-${agent.name}`;
  const sourceMetadataPath = join(rootPath, "apps", packageSlug, "source-metadata.json");
  if (!existsSync(sourceMetadataPath)) continue;

  const packageFile = `${packageSlug}.zip`;
  const destinationPath = join(outputPath, packageFile);
  const sources = [
    join(artifactPath, packageFile),
    join(rootPath, "apps", packageSlug, "appPackage", "build", "appPackage.dev.zip")
  ];
  const sourcePath = sources.find((path) => existsSync(path));

  if (sourcePath) {
    copyFileSync(sourcePath, destinationPath);
  } else if (existsSync(destinationPath)) {
    rmSync(destinationPath);
  }
}

console.log("Staged available M365 agent packages for the static site.");